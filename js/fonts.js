function styleStrokes(raw, style, seed) {
  const slant = Math.tan(((style.slant || 0) * Math.PI) / 180);
  const sx = style.width ?? 1;
  const rand = mulberry32((seed * 97 + 13) >>> 0);
  const dy = (rand() - 0.5) * 2 * (style.bounce || 0);
  const sheared = raw.map((stroke) => stroke.map((p) => ({
    x: (p.x + p.y * slant) * sx,
    y: p.y + dy,
  })));
  return sheared.map((stroke, i) => wobble(stroke, style.wobble || 0, seed * 47 + i * 19));
}

const cache = new Map();

export function makeSampleFont(id) {
  const style = SAMPLE_FONTS.find((f) => f.id === id) || SAMPLE_FONTS[0];
  if (cache.has(style.id)) return cache.get(style.id);
  const glyphs = {};
  for (const [ch, recipe] of Object.entries(SKEL)) {
    const raw = strokesFrom(recipe);
    glyphs[ch] = style.seeds.map((seed) => {
      const strokes = styleStrokes(raw, style, seed + ch.charCodeAt(0) * 13);
      const b = boundsOfStrokes(strokes);
      return {
        width: Math.max((WIDTH[ch] || 0.7) * (style.width || 1), b.width, 0.2),
        strokes,
        sample: style.id,
      };
    });
  }
  const font = { glyphs, words: {}, stamps: [], sample: style.id };
  cache.set(style.id, font);
  return font;
}

export function userOnlyMap(map = {}) {
  const out = {};
  for (const [key, list] of Object.entries(map)) {
    const keep = (list || []).filter((g) => !g.demo && !g.sample);
    if (keep.length) out[key] = keep;
  }
  return out;
}

export function stripDemoInk(lib = {}) {
  return {
    ...lib,
    glyphs: userOnlyMap(lib.glyphs),
    words: userOnlyMap(lib.words),
    stamps: (lib.stamps || []).filter((s) => !s.demo),
  };
}

export function hasUserGlyphs(lib = {}) {
  return Object.values(userOnlyMap(lib.glyphs)).some((list) => list.length);
}

export function composeLibrary(userLib, fontId) {
  const stamps = (userLib?.stamps || []).filter((s) => !s.demo);
  if (!fontId || fontId === CUSTOM_FONT_ID) {
    return {
      glyphs: userOnlyMap(userLib?.glyphs),
      words: userOnlyMap(userLib?.words),
      stamps,
    };
  }
  const sample = makeSampleFont(fontId);
  return { glyphs: sample.glyphs, words: {}, stamps };
}
